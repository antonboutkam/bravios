import { catalogOutput } from './catalog-output.mjs';
import {readFile,writeFile,realpath} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {loadStructureCatalog,validateStructureTiles} from '../public_html/engine/structures/load-catalog.mjs';
import {ENEMY_CATALOG} from '../public_html/engine/enemies/catalog.mjs';
export async function discoverStructures(directory=new URL('../public_html/gameplay/',import.meta.url)){
 const root=await realpath(directory),webRoot=path.dirname(root);
 const profiles=await loadStructureCatalog(async relative=>{
  const file=await realpath(path.join(webRoot,relative));if(!file.startsWith(root+path.sep))throw new Error(`${relative}: bestand buiten gameplay.`);
  try{return JSON.parse(await readFile(file,'utf8'));}catch(error){if(error instanceof SyntaxError)throw new Error(`${relative}: ongeldige JSON.`);throw error;}
 });
 validateStructureTiles(profiles,ENEMY_CATALOG);
 await Promise.all(profiles.flatMap(c=>[...Object.values(c.visuals),...(c.terrain?[{...c.terrain,terrain:true}]:[])].map(async v=>{
  const file=await realpath(path.join(webRoot,v.image));if(!file.startsWith(path.join(root,c.category,c.id)+path.sep))throw new Error(`${v.image}: afbeelding buiten structuurmap.`);
  const png=await readFile(file);
  if(png.length<33||!png.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])))throw new Error(`${v.image}: ongeldige PNG.`);
  const w=png.readUInt32BE(16),h=png.readUInt32BE(20);
  if(v.terrain?w<5*96||h<4*96||Math.abs(w/h-5/4)>.01:w!==v.frameWidth*v.frames||h!==v.frameHeight)throw new Error(`${v.image}: PNG-afmetingen passen niet bij de configuratie.`);
 })));
 return profiles;
}
export async function prepareStructures(directory=new URL('../public_html/gameplay/',import.meta.url)){
 const profiles=await discoverStructures(directory),file=catalogOutput(directory, 'structures');
 const source='// Generated by scripts/prepare-structures.mjs. Edit structures.json and structure.json files.\nexport const STRUCTURE_CATALOG = '+JSON.stringify(profiles,null,2)+';\n';
 let before;try{before=await readFile(file,'utf8');}catch(error){if(error.code!=='ENOENT')throw error;}
 if(before!==source)await writeFile(file,source);return profiles;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(`${(await prepareStructures()).length} structuren gecontroleerd.`);
