import { readFile,writeFile,realpath } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { loadEnemyCatalog } from '../public_html/enemies/load-catalog.mjs';
export async function discoverEnemies(directory=new URL('../public_html/enemies/',import.meta.url)) {
  const root=await realpath(directory),gameRoot=path.dirname(root);
  const profiles=await loadEnemyCatalog(async relative=>{
    const filename=path.resolve(gameRoot,relative),resolved=await realpath(filename);
    if(!resolved.startsWith(root+path.sep))throw new Error(`${relative}: bestand buiten enemies.`);
    try{return JSON.parse(await readFile(resolved,'utf8'));}catch(error){if(error instanceof SyntaxError)throw new Error(`${relative}: ongeldige JSON.`);throw error;}
  });
  for(const c of profiles)for(const a of Object.values(c.animations)){
    const filename=await realpath(path.join(gameRoot,a.image));
    if(!filename.startsWith(path.join(root,c.group,c.id)+path.sep))throw new Error(`${a.image}: afbeelding buiten vijandmap.`);
    const png=await readFile(filename);
    if(png.length<33||!png.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10]))||png.readUInt32BE(16)!==a.frameWidth*a.frames||png.readUInt32BE(20)!==a.frameHeight)throw new Error(`${a.image}: ongeldige PNG of afmetingen passen niet bij de animatie.`);
  }
  return profiles;
}
export async function prepareEnemies(directory=new URL('../public_html/enemies/',import.meta.url)) {
  const profiles=await discoverEnemies(directory);
  const output=path.join(fileURLToPath(directory instanceof URL?directory:new URL('file://'+path.resolve(directory)+'/')),'catalog.mjs');
  const source='// Generated by scripts/prepare-enemies.mjs. Edit enemies.json and enemy.json files.\nexport const ENEMY_CATALOG = '+JSON.stringify(profiles,null,2)+';\n';
  let previous;try{previous=await readFile(output,'utf8');}catch(error){if(error.code!=='ENOENT')throw error;}
  if(source!==previous)await writeFile(output,source);
  return profiles;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(`${(await prepareEnemies()).length} vijanden en bazen gecontroleerd.`);
